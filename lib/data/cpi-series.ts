/** הבסיס שבו מפורסם כל חודש (תחילתו בינואר של השנה המצוינת). */
export function baseOfMonth(month: string): CpiBaseId {
  const year = Number(month.slice(0, 4));
  if (year >= 2025) return '2024';
  if (year >= 2023) return '2022';
  if (year >= 2021) return '2020';
  return '2018';
}

