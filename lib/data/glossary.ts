/** מחזיר מונח לפי ה-slug (id). */
export function getTermBySlug(slug: string): GlossaryTerm | undefined {
  return ALL_TERMS.find((t) => t.id === slug);
}

/** מונחים קשורים: עד 6 — תחילה מאותה אות, ואז משלימים לפי סדר הרשימה. */
export function getRelatedTerms(slug: string, limit = 6): GlossaryTerm[] {
  const current = getTermBySlug(slug);
  if (!current) return [];
  const sameLetter = ALL_TERMS.filter((t) => t.id !== slug && t.letter === current.letter);
  const rest = ALL_TERMS.filter((t) => t.id !== slug && t.letter !== current.letter);
  return [...sameLetter, ...rest].slice(0, limit);
}
